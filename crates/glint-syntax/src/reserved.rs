// X.680 (02/2021) 12.38 does not list SUCCESSORS or DESCENDANTS (13.16 quotes them), so they are matched contextually.

/// Whether `name` is an X.680 reserved word (12.38).
pub fn is_reserved(name: &str) -> bool {
    RESERVED_WORDS.contains(&name)
}

/// Whether `name` has no lower-case letters (an `objectclassreference` shape, X.681 7.1).
pub fn is_all_upper(name: &str) -> bool {
    !name.chars().any(|c| c.is_ascii_lowercase())
}

/// Whether `name` is reserved only by editions after X.208 (1988), so old modules may legitimately use it as a name.
pub fn is_later_edition_word(name: &str) -> bool {
    LATER_EDITION_WORDS.contains(&name)
}
