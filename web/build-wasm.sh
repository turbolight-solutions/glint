#!/usr/bin/env bash
# Builds glint-wasm and its JavaScript bindings into web/src/wasm (git-ignored), with the data schema the code reads
# in web/src/wasm/schema.ts. Needs the wasm32-unknown-unknown target and the wasm-bindgen CLI of the version that
# Cargo.lock pins for the wasm-bindgen crate.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
cargo build --manifest-path "$root/Cargo.toml" --locked --profile wasm --target wasm32-unknown-unknown -p glint-wasm
out="$root/web/src/wasm"
rm -rf "$out"
mkdir -p "$out"
wasm-bindgen --target web --out-dir "$out" "$root/target/wasm32-unknown-unknown/wasm/glint_wasm.wasm"
schema="$(sed -n 's/^pub const SCHEMA: u32 = \([0-9][0-9]*\);$/\1/p' "$root/crates/glint-corpus/src/data.rs")"
if [ -z "$schema" ]; then
  echo "build-wasm.sh: cannot read SCHEMA from crates/glint-corpus/src/data.rs" >&2
  exit 1
fi
printf '// Generated by build-wasm.sh from glint-corpus: the data schema this code reads.\nexport const SCHEMA = %s;\n' "$schema" > "$out/schema.ts"
